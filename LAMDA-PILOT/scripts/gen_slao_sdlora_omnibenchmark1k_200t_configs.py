"""SLAO and SD-LoRA, full oracle regime, OmniBenchmark-1k-200t (2026-11-04
user request) -- chained after the SUN397/Food-101 re-run in
scripts/slao_sdlora_sun397_food101_rerun_then_omni200t.slurm.

Task split: established directly from exps/omnibenchmark1k_200t/cllora_s1993.json
(the project's existing 200t reference, used by the other 8 methods) --
dataset="omnibenchmark1k", init_cls=5, increment=5 (200 tasks). This is
DISTINCT from the 100t variant's own init_cls=10/increment=10 -- the dataset
key is identical in both ("omnibenchmark1k"), only the split differs, so this
was verified directly rather than assumed, per the 2026-11-03 SUN397/Food-101
task-split bug.

Learning rate: per explicit user instruction, reuse the SAME LR the 100t
split already uses for this dataset (never independently tuned on 200t) --
slao=0.001, sdlora=0.005, i.e. LR_BY_DATASET["*"]["omnibenchmark1k"] from
scripts/gen_slao_sdlora_wave1_datasets_configs.py, copied here as a literal
so this generator has no import-order dependency on that file.

Naming collision, deliberately avoided: the 100t variant's own config
(generated by gen_slao_sdlora_wave1_datasets_configs.py) uses
dataset="omnibenchmark1k" with prefix
"slao_sdlora_wave1_datasets_{method}_omnibenchmark1k_s{seed}". Since the
`dataset` field is literally identical between the 100t and 200t variants,
reusing that same prefix pattern here would collide tag-for-tag with the
100t run's own final_metrics/output files (scripts/_bankcap_run_done.py's
resumability check keys off exactly this tag). The prefix here is instead
"slao_sdlora_wave1_datasets_{method}_omnibenchmark1k_200t_s{seed}" -- an
explicit "_200t" suffix -- so the two variants can never be confused with
or silently skip each other.

2 methods x 3 seeds = 6 runs.
"""
import json
import os

OUT_DIR = "exps/slao_sdlora_wave1_datasets"
SEEDS = [1993, 1996, 1999]
DATASET = "omnibenchmark1k"
INIT_CLS = 5
INCREMENT = 5

SOURCE_CONFIGS = {
    "slao": "exps/slao_lr_tune_cifar224/slao_lr_tune_cifar224_1e-3_s1993.json",
    "sdlora": "exps/sdlora_lr_tune_cifar224/sdlora_lr_tune_cifar224_5e-3_s1993.json",
}

# same LR the 100t omnibenchmark1k config already uses (see module docstring)
LR_BY_METHOD = {"slao": 0.001, "sdlora": 0.005}

STRIP_KEYS = ("stop_after_tasks", "prefix")


def main():
    written = []
    for method, src_path in SOURCE_CONFIGS.items():
        base = json.load(open(src_path))
        for key in STRIP_KEYS:
            base.pop(key, None)
        out_dir = os.path.join(OUT_DIR, method)
        os.makedirs(out_dir, exist_ok=True)

        for seed in SEEDS:
            cfg = dict(base)
            cfg["dataset"] = DATASET
            cfg["seed"] = [seed]
            cfg["init_cls"] = INIT_CLS
            cfg["increment"] = INCREMENT
            cfg["init_lr"] = LR_BY_METHOD[method]
            cfg["prefix"] = "slao_sdlora_wave1_datasets_{}_omnibenchmark1k_200t_s{}".format(method, seed)
            path = os.path.join(out_dir, "omnibenchmark1k_200t_s{}.json".format(seed))
            json.dump(cfg, open(path, "w"), indent=2)
            written.append(path)

    print("wrote {} configs under {}/".format(len(written), OUT_DIR))


if __name__ == "__main__":
    main()
